(async () => {
  const input = JSON.parse(process.argv[2])
  const trace = event => { if (process.env.KNOWBOOK_TRACE_COVERAGE_DRAFT) process.stderr.write(`[coverage-cold] ${event}\n`) }
  const { captureReopenedRootKnowledgeConservationPlan3 } = await import('../src/main/database/restore-knowledge-root3-read.ts')
  const { reopenRootRestoreIdentityPlan3 } = await import('../src/main/database/restore-knowledge-identity3-read.ts')
  const { reopenRootRestoreReferencePlan3 } = await import('../src/main/database/restore-knowledge-reference3-read.ts')
  const { reopenRootRestoreSqlAssetStage5 } = await import('../src/main/database/restore-knowledge-sql-asset-stage5.ts')
  const { reopenRootRestoreFinalAssetSql5 } = await import('../src/main/database/restore-knowledge-derived-stage4.ts')
  const { reopenRootRestoreCoverageSql } = await import('../src/main/database/restore-knowledge-stage3-history-sql.ts')
  const original = await captureReopenedRootKnowledgeConservationPlan3(input.original)
  const identity = await reopenRootRestoreIdentityPlan3(original.knowledgePlan, input.identity)
  const reference = await reopenRootRestoreReferencePlan3(identity.plan, input.reference)
  trace('reference')
  const combined = await reopenRootRestoreSqlAssetStage5(reference.plan, input.combined)
  const final = await reopenRootRestoreFinalAssetSql5(reference.plan, combined.stage, input.final)
  trace('final')
  const coverage = await reopenRootRestoreCoverageSql(reference.plan, final.derived.stage, input.coverage)
  process.stdout.write(JSON.stringify({ pid: process.pid, manifestHash: coverage.manifestHash, value: coverage.value }))
})().catch(error => { console.error(error); process.exitCode = 1 })
