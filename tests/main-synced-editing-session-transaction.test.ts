import assert from 'node:assert/strict'
import test from 'node:test'
import Database from 'better-sqlite3'
import { randomUUID } from 'node:crypto'
import type { SyncedUpdateGroupInput } from '../src/shared/synced-blocks'
import { withCanonicalSearchFixture } from './helpers/canonical-search-fixture'

test('the exact session epoch is checked inside the original writer transaction after a real SQL boundary change, before any business write or ACK',
  {concurrency:false},()=>withCanonicalSearchFixture(f=>{
    const sender={},opened=f.store.openSyncedEditingSession(sender,{kind:'instance',hostDocumentId:f.hostId,instanceId:f.firstInstanceId,groupId:f.searchGroupId})
    assert.equal(opened.status,'ready');if(opened.status!=='ready')return
    const snapshot=opened.snapshot!;const binding=opened.instance!
    const input:SyncedUpdateGroupInput={groupId:snapshot.groupId,expectedRevision:snapshot.revision,expectedTopologyRevision:snapshot.topologyRevision,
      expectedInstanceBinding:{instanceId:binding.instanceId,hostDocumentId:binding.hostDocumentId,bindingVersion:binding.bindingVersion},clientOperationId:randomUUID(),
      blocks:snapshot.blocks.map(({createdAt:_birth,...block})=>({...block,content:block.content+' must rollback'}))}
    const before=f.db.prepare('SELECT * FROM synced_group_blocks WHERE group_id=? ORDER BY sort_order').all(f.searchGroupId)
    const prototype=Database.prototype as unknown as {prepare:(this:Database.Database,sql:string)=>Database.Statement},prepare=prototype.prepare
    let injected=false,inside=false
    prototype.prepare=function(this:Database.Database,sql:string){
      if(this===f.db&&!injected&&sql==='SELECT workspace_scope,recovery_epoch FROM synced_workspace_state WHERE singleton=1'){
        inside=this.inTransaction;assert.equal(inside,true)
        injected=true;prepare.call(this,'UPDATE synced_workspace_state SET recovery_epoch=? WHERE singleton=1').run(randomUUID())
      }
      return prepare.call(this,sql)
    }
    try{assert.throws(()=>f.store.invokeSyncedEditingSession(sender,{sessionId:opened.session.sessionId,method:'updateSyncedBlockGroup',input}),/workspace epoch changed/)}
    finally{prototype.prepare=prepare}
    assert.equal(injected,true);assert.equal(inside,true)
    assert.deepEqual(f.db.prepare('SELECT * FROM synced_group_blocks WHERE group_id=? ORDER BY sort_order').all(f.searchGroupId),before)
    assert.equal(f.db.prepare('SELECT 1 FROM synced_operations WHERE client_operation_id=?').get(input.clientOperationId),undefined)
    assert.equal((f.db.prepare('SELECT recovery_epoch FROM synced_workspace_state WHERE singleton=1').get() as {recovery_epoch:string}).recovery_epoch,opened.session.recoveryEpoch,
      'The actual adversarial boundary UPDATE was in the same rejected transaction and rolled back too')
  }))

test('a real SQLite AFTER INSERT failure at the original ACK rolls back session content, history and receipt before any successful return',
  {concurrency:false},()=>withCanonicalSearchFixture(f=>{
    const sender={},opened=f.store.openSyncedEditingSession(sender,{kind:'instance',hostDocumentId:f.hostId,instanceId:f.firstInstanceId,groupId:f.searchGroupId})
    assert.equal(opened.status,'ready');if(opened.status!=='ready')return
    const snapshot=opened.snapshot!,binding=opened.instance!,operationId=randomUUID()
    const input:SyncedUpdateGroupInput={groupId:snapshot.groupId,expectedRevision:snapshot.revision,expectedTopologyRevision:snapshot.topologyRevision,
      expectedInstanceBinding:{instanceId:binding.instanceId,hostDocumentId:binding.hostDocumentId,bindingVersion:binding.bindingVersion},clientOperationId:operationId,
      blocks:snapshot.blocks.map(({createdAt:_birth,...block})=>({...block,content:block.content+' transaction failure'}))}
    const tables=['synced_groups','synced_group_blocks','synced_group_history','synced_operations','block_identities']
    const state=()=>tables.map(table=>[table,f.db.prepare('SELECT * FROM '+table+' ORDER BY _rowid_').all()])
    const before=state()
    // The UUID is generated by this test; it contains no quotes or SQL syntax.
    f.db.exec(`CREATE TEMP TRIGGER canonical_session_late_failure AFTER INSERT ON main.synced_operations
      WHEN NEW.client_operation_id='${operationId}' BEGIN SELECT RAISE(ABORT,'actual canonical session late SQL failure'); END`)
    try{assert.throws(()=>f.store.invokeSyncedEditingSession(sender,{sessionId:opened.session.sessionId,method:'updateSyncedBlockGroup',input}),/actual canonical session late SQL failure/)}
    finally{f.db.exec('DROP TRIGGER temp.canonical_session_late_failure')}
    assert.deepEqual(state(),before)
    assert.equal(f.store.invokeSyncedEditingSession(sender,{sessionId:opened.session.sessionId,method:'getSyncedOperation',input:{clientOperationId:operationId}}).status,'unknown')
  }))
