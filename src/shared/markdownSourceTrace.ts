/** Positions are absolute UTF-16 offsets into the exact supplied raw source.
 * A null character was generated by the parser. A boundary has multiple
 * candidates when deleted syntax separates its two neighbours. */
export interface MarkdownSourceContentTrace {
  readonly kind: 'exact' | 'opaque-generated'
  readonly index: number
  readonly content: string
  readonly starts: readonly (number | null)[]
  readonly ends: readonly (number | null)[]
  readonly boundaries: readonly (readonly number[])[]
}
export type MarkdownSourceEmission =
  | { kind: 'raw' | 'paragraph'; startLine: number; endLine: number }
  | { kind: 'quote'; node: MarkdownNode }
  | { kind: 'list'; item: MarkdownNode; simple: boolean; projectedFrom: number; taskLength: number }
  | { kind: 'token'; token: Token; stripFinalLF?: boolean }
  | { kind: 'empty' }
export interface MarkdownSourceTracePort {
  parse(source: string, environment: Record<string, unknown>): Token[]
  emit(block: MarkdownRenderableBlock, index: number, emission: MarkdownSourceEmission): void
}
type Text = { content: string; starts: (number | null)[]; ends: (number | null)[]; empty: number[] }
type Range = { from: number; to: number }
function fail(message: string): never { throw new Error('Untraceable strict Markdown source: ' + message) }
const unique = (values: readonly number[]) => [...new Set(values)]
function boundary(value: Text, at: number): number[] {
  if (!value.content.length) return value.empty
  const points: number[] = []
  if (at > 0 && value.ends[at - 1] !== null) points.push(value.ends[at - 1]!)
  if (at < value.content.length && value.starts[at] !== null) points.push(value.starts[at]!)
  return unique(points)
}
function slice(value: Text, from: number, to = value.content.length): Text {
  return { content: value.content.slice(from, to), starts: value.starts.slice(from, to), ends: value.ends.slice(from, to),
    empty: from === to ? boundary(value, from) : [] }
}
function generated(content: string): Text {
  return { content, starts: Array<number | null>(content.length).fill(null), ends: Array<number | null>(content.length).fill(null), empty: [] }
}
function concat(values: readonly Text[]): Text {
  return { content: values.map(value => value.content).join(''), starts: values.flatMap(value => value.starts),
    ends: values.flatMap(value => value.ends), empty: unique(values.flatMap(value => value.empty)) }
}
function replace(value: Text, from: number, to: number, insert: string): Text {
  return concat([slice(value, 0, from), generated(insert), slice(value, to)])
}
function trim(value: Text, pattern = /^[\t\n\r ]+|[\t\n\r ]+$/g): Text {
  const matches = [...value.content.matchAll(pattern)]
  for (const match of matches.reverse()) value = replace(value, match.index, match.index + match[0].length, '')
  return value
}
const trimBlank = (value: Text) => trim(value, /^(?:[ \t]*\n)+|(?:\n[ \t]*)+$/g)
function mapProjection(value: Text, content: string, starts?: readonly number[], ends?: readonly number[]): Text {
  if (!starts || !ends) {
    if (content !== value.content) fail('a transformation did not supply its source positions')
    return value
  }
  return { content, starts: starts.map(at => value.starts[at] ?? null), ends: ends.map(at => value.ends[at - 1] ?? null),
    empty: content.length ? [] : boundary(value, 0) }
}
function decode(value: Text): Text {
  const projection = decodeNativeLiteralText(value.content)
  return mapProjection(value, projection.content, projection.starts, projection.ends)
}
function normalizedSource(raw: string): Text {
  const parts: string[] = [], starts: number[] = [], ends: number[] = []
  for (let at = raw.startsWith('\uFEFF') ? 1 : 0; at < raw.length; at++) {
    const end = raw[at] === '\r' && raw[at + 1] === '\n' ? at + 2 : at + 1
    parts.push(raw[at] === '\r' ? '\n' : raw[at]); starts.push(at); ends.push(end); at = end - 1
  }
  return { content: parts.join(''), starts, ends, empty: [raw.startsWith('\uFEFF') ? 1 : 0] }
}
function splitLines(value: Text): Text[] {
  const values: Text[] = []
  let start = 0
  for (let at = 0; at < value.content.length; at++) if (value.content[at] === '\n') {
    values.push(slice(value, start, at)); start = at + 1
  }
  values.push(slice(value, start)); return values
}
function expandTabs(value: Text): Text {
  const prefix = /^[ \t]*(?:[-+*]|\d{1,9}[.)]|>)?[ \t]*/.exec(value.content)?.[0] ?? ''
  const parts: Text[] = []
  let column = 0
  for (let at = 0; at < prefix.length; at++) {
    const width = prefix[at] === '\t' ? 4 - column % 4 : 1
    parts.push(prefix[at] === '\t' ? generated(' '.repeat(width)) : slice(value, at, at + 1)); column += width
  }
  parts.push(slice(value, prefix.length)); return concat(parts)
}
function stripList(value: Text): Text {
  const lines = splitLines(value), first = expandTabs(lines[0])
  const marker = /^ *(?:[-+*]|\d{1,9}[.)])(?= |$)/.exec(first.content)
  if (!marker) return value
  const remaining = first.content.slice(marker[0].length), padding = /^ */.exec(remaining)![0].length
  const indent = marker[0].length + (!remaining.trim() || padding > 4 ? 1 : padding)
  const parts = [slice(first, Math.min(indent, first.content.length))]
  let offset = lines[0].content.length
  for (const line of lines.slice(1)) {
    parts.push(slice(value, offset, offset + 1)); offset += line.content.length + 1
    const expanded = expandTabs(line), spaces = /^ */.exec(expanded.content)![0].length
    parts.push(slice(expanded, Math.min(indent, spaces)))
  }
  return concat(parts)
}
function protect(value: Text, children?: MarkdownNode[], firstLine = 0): Text {
  let mapped = value
  const edit = (from: number, to: number, insert: string) => { mapped = replace(mapped, from, to, insert) }
  const content = children ? protectContainerParagraphs(value.content, children, firstLine, edit)
    : protectParagraphContinuations(value.content, edit)
  if (content !== mapped.content) fail('paragraph protection lost its edit trace')
  return mapped
}

/** Mirrors StateBlock.getLines at the moment the real rule calls it, including
 * temporary list/blockquote bMarks, bsCount and tShift. It never searches for
 * emitted text. The original method still supplies the parser's actual value. */
function getLines(state: StateBlock, source: Text, begin: number, end: number, indent: number, keepLastLF: boolean): Text {
  if (begin >= end) return { ...generated(''), empty: boundary(source, state.bMarks[begin] ?? source.content.length) }
  const parts: Text[] = []
  for (let line = begin; line < end; line++) {
    let lineIndent = 0, first = state.bMarks[line]
    const lineStart = first, last = state.eMarks[line] + (line + 1 < end || keepLastLF ? 1 : 0)
    while (first < last && lineIndent < indent) {
      const ch = state.src.charCodeAt(first)
      if (ch === 9 || ch === 32) lineIndent += ch === 9 ? 4 - (lineIndent + state.bsCount[line]) % 4 : 1
      else if (first - lineStart < state.tShift[line]) lineIndent++
      else break
      first++
    }
    if (lineIndent > indent) parts.push(generated(' '.repeat(lineIndent - indent)))
    parts.push(slice(source, first, Math.min(last, source.content.length)))
  }
  return concat(parts)
}
type Frame = { name: string; state: StateBlock; start: number; lines?: Text }
type RawTraceCapture = { states: WeakMap<StateBlock, Text>; owners: WeakMap<Token[], Token>;
  inlineTexts: WeakMap<Token[], Text>; scopes: Array<{ scope: object; value: Text; reason: string }> }

/** A temporary observer surrounds one synchronous parse. All original rules
 * execute unchanged and are restored even on errors. No public parse allocates
 * maps, and nested native block parsing gets its actual candidate slice. */
function captureTokens(source: Text, environment: Record<string, unknown>, tokenText: WeakMap<Token, Text>, raw?: RawTraceCapture): Token[] {
  const states = raw?.states ?? new WeakMap<StateBlock, Text>(), frames: Frame[] = []
  const previousState = markdownEngine.block.State
  const previousInline = markdownEngine.inline.parse
  const rawObserver = environment.markdownRawOccurrences
  const sameObservation = (env: Record<string, unknown>) => env === environment
    || rawObserver !== undefined && env.markdownRawOccurrences === rawObserver
  const rules = markdownEngine.block.ruler.__rules__.map(rule => ({ ...rule }))
  const sourceFor = (src: string): Text => {
    const frame = frames.at(-1)
    if (!frame) return { ...source, content: src }
    if (frame.name === 'native_container' && frame.lines) {
      const candidate = frame.lines, lines = candidate.content.split('\n')
      const openingSource = /^(?:[ \t]*)(<(?:[a-z][\w-]*)(?=[\s>])(?:[^"'<>]|"[^"]*"|'[^']*')*>)/i.exec(candidate.content)?.[1]
      const opening = openingSource && parseNativeContainerOpening(openingSource)
      if (opening) {
        const title = opening.titleTag ? nativeContainerTitleLines(lines, 1, opening) : null
        const bodyLine = title?.endLine ?? 1
        const from = lines.slice(0, bodyLine).reduce((length, line) => length + line.length + 1, 0)
        const value = slice(candidate, from, from + src.length)
        if (value.content === src) return value
      }
    }
    // Legacy HTML/footnote subtrees are retained by their enclosing raw block.
    // Should an emitted block unexpectedly depend on one, emit fails closed.
    return generated(src)
  }
  class TraceState extends previousState {
    constructor(...args: ConstructorParameters<typeof previousState>) { super(...args); states.set(this, sourceFor(this.src)) }
    override getLines(begin: number, end: number, indent: number, keepLastLF: boolean): string {
      const actual = super.getLines(begin, end, indent, keepLastLF)
      const value = getLines(this, states.get(this)!, begin, end, indent, keepLastLF)
      if (actual !== value.content) fail('StateBlock.getLines changed without a matching trace')
      const frame = frames.at(-1)
      if (frame?.state === this) frame.lines = value
      return actual
    }
  }
  const actualTokenText = (token: Token): Text | undefined => {
    let value = tokenText.get(token)
    if (value && token.meta?.nativeLiteralEscaped && value.content !== token.content) value = decode(value)
    return value?.content === token.content ? value : undefined
  }
  const run = () => {
  try {
    markdownEngine.block.State = TraceState
    if (raw) markdownEngine.inline.parse = (content, engine, env, tokens) => {
      if (!sameObservation(env)) return previousInline.call(markdownEngine.inline, content, engine, env, tokens)
      const owner = raw.owners.get(tokens), value = owner && actualTokenText(owner)
      if (value?.content === content) raw.inlineTexts.set(tokens, value)
      else if (!isMarkdownSourceImageAlt(env)) raw.scopes.push({ scope: tokens, value: generated(content), reason: 'unmapped-inline-scope' })
      return previousInline.call(markdownEngine.inline, content, engine, env, tokens)
    }
    for (const rule of rules) markdownEngine.block.ruler.at(rule.name, (state, start, end, silent) => {
      if (raw && !sameObservation(state.env)) return rule.fn(state, start, end, silent)
      const frame: Frame = { name: rule.name, state, start }, first = state.tokens.length
      frames.push(frame)
      try {
        const accepted = rule.fn(state, start, end, silent)
        if (!accepted || silent) return accepted
        const emitted = state.tokens.slice(first), input = states.get(state)!
        if (['paragraph', 'lheading'].includes(rule.name)) {
          const inline = emitted.find(token => token.type === 'inline')
          if (inline && frame.lines) tokenText.set(inline, trim(frame.lines))
        } else if (rule.name === 'heading') {
          const inline = emitted.find(token => token.type === 'inline')
          if (inline) {
            let from = state.bMarks[start] + state.tShift[start]
            while (state.src[from] === '#') from++
            let to = state.skipSpacesBack(state.eMarks[start], from)
            const hashes = state.skipCharsBack(to, 35, from)
            if (hashes > from && /[ \t]/.test(state.src[hashes - 1])) to = hashes
            tokenText.set(inline, trim(slice(input, from, to)))
          }
        } else if (rule.name === 'frontmatter') {
          const token = emitted.find(token => token.type === 'frontmatter')
          if (token?.map) tokenText.set(token, slice(input, state.bMarks[token.map[0]], state.eMarks[token.map[1] - 1]))
        } else if (['fence', 'code'].includes(rule.name)) {
          const token = emitted.find(token => token.type === 'fence' || token.type === 'code_block')
          if (token && frame.lines) tokenText.set(token, token.type === 'code_block' ? concat([frame.lines, generated('\n')]) : frame.lines)
        } else if (rule.name === 'math_block') {
          const token = emitted.find(token => token.type === 'math_block')
          if (token?.map) {
            const last = token.map[1] - 1, from = state.bMarks[start] + state.tShift[start] + token.markup.length
            const closeLength = token.markup.length
            if (last === start) tokenText.set(token, slice(trimEnd(slice(input, from, state.eMarks[start])), 0,
              trimEnd(slice(input, from, state.eMarks[start])).content.length - closeLength))
            else {
              const initial = slice(input, from, state.eMarks[start])
              const lastLine = trimEnd(slice(input, state.bMarks[last] + state.tShift[last], state.eMarks[last]))
              const final = slice(lastLine, 0, lastLine.content.length - closeLength)
              const values = [
                { value: initial, after: state.eMarks[start] },
                { value: frame.lines ?? generated(''), after: state.eMarks[last - 1] },
                { value: final, after: state.eMarks[last] }
              ].filter(part => part.value.content !== '')
              const parts: Text[] = []
              for (let index = 0; index < values.length; index++) {
                if (index) {
                  const after = values[index - 1].after, newline = slice(input, after, after + 1)
                  // The rule joins retained components. Only an actual adjacent
                  // source newline is mapped; removed empty lines remain gaps.
                  parts.push(newline.content === '\n' ? newline : generated('\n'))
                }
                parts.push(values[index].value)
              }
              tokenText.set(token, concat(parts))
            }
          }
        } else if (rule.name === 'native_container' && frame.lines) {
          const lines = frame.lines.content.split('\n'), opening = parseNativeContainerOpening(lines[0].trim())
          const header = opening?.titleTag ? nativeContainerTitleLines(lines, 1, opening) : null
          const title = opening && header ? parseNativeContainerTitle(header.source, opening) : null
          const inline = emitted.find(token => token.meta?.nativeContainerTitle)
          if (inline && title) {
            const from = lines[0].length + 1 + lines[1].length - lines[1].trimStart().length + title.offset
            tokenText.set(inline, slice(frame.lines, from, from + title.content.length))
          }
        }
        if (raw) {
          for (const token of emitted) if (token.type === 'inline' && token.children) raw.owners.set(token.children, token)
          if (['table', 'footnote_def', 'html_details', 'html_figure'].includes(rule.name)) {
            const from = state.bMarks[start], last = Math.max(start, state.line - 1)
            raw.scopes.push({ scope: emitted[0] ?? state, value: slice(input, from, state.eMarks[last]), reason: rule.name + '-scope' })
          }
        }
        return accepted
      } finally { frames.pop() }
    }, { alt: rule.alt })
    return markdownEngine.parse(source.content, environment)
  } finally {
    markdownEngine.block.State = previousState
    markdownEngine.inline.parse = previousInline
    for (const rule of rules) markdownEngine.block.ruler.at(rule.name, rule.fn, { alt: rule.alt })
  }
  }
  return raw ? withMarkdownSourceSliceObserver((token, from, to, target) => {
    const value = actualTokenText(token)
    if (value) {
      tokenText.set(target, slice(value, from, to))
      if (target.children) raw.owners.set(target.children, target)
    }
  }, run) : run()
}
const trimEnd = (value: Text) => trim(value, /[\s\uFEFF\xA0]+$/g)

/** Actual parser text and its exact supplied-buffer projection. Gaps can be
 * real structural indentation; generated characters are never certified. */
export interface MarkdownSourceRawSpan {
  readonly from: number
  readonly to: number
  readonly raw: string
  readonly parsed: string
  readonly projection: Readonly<{ starts: readonly number[]; ends: readonly number[]; boundaries: readonly (readonly number[])[] }>
}
export interface MarkdownSourceRawTrace {
  parse(environment: Record<string, unknown>): Token[]
  /** The actual block/core inline token that supplied this parser's array. */
  inlineOwner(state: StateInline): Token | null
  inlineRange(state: StateInline, from: number, to: number): MarkdownSourceRawSpan | null
  referenceRange(state: StateBlock, startLine: number, parserSource: string, from: number, to: number): MarkdownSourceRawSpan | null
  referenceUse(state: StateBlock, token: Token): MarkdownSourceRawSpan | null
  readonly scopes: readonly Readonly<{ scope: object; range: MarkdownSourceRawSpan | null; reason: string }>[]
}

/** A cold, one-parse receipt. Its inline projections are keyed by the actual
 * output token array, not by content, URL, block ID or an equivalent parse. */
export function createMarkdownSourceRawTrace(rawSource: string): MarkdownSourceRawTrace {
  const tokenText = new WeakMap<Token, Text>(), capture: RawTraceCapture = {
    states: new WeakMap(), owners: new WeakMap(), inlineTexts: new WeakMap(), scopes: []
  }
  let used = false
  const span = (value: Text | undefined, from: number, to: number): MarkdownSourceRawSpan | null => {
    if (!value || !validRange(value.content.length, from, to)) return null
    const part = slice(value, from, to), startPoints = boundary(value, from)
    if (from === to) {
      if (startPoints.length !== 1) return null
      const point = startPoints[0]
      for (let at = 0; at <= value.content.length; at++) if (at !== from && boundary(value, at).includes(point)) return null
      return Object.freeze({ from: point, to: point, raw: '', parsed: '', projection: Object.freeze({
        starts: Object.freeze([]), ends: Object.freeze([]), boundaries: Object.freeze([Object.freeze([point])]) }) })
    }
    const starts = part.starts, ends = part.ends
    if (starts.some(at => at === null) || ends.some(at => at === null)) return null
    const first = starts[0]!, last = ends.at(-1)!
    // Do not cut an indivisible decoded unit or silently reverse source order.
    if (first < 0 || last < first || last > rawSource.length
      || from > 0 && value.ends[from - 1] !== null && value.ends[from - 1]! > first
      || to < value.content.length && value.starts[to] !== null && value.starts[to]! < last) return null
    for (let at = 0; at < starts.length; at++) if (ends[at]! < starts[at]!
      || at && (starts[at]! < starts[at - 1]! || ends[at]! < ends[at - 1]!)) return null
    return Object.freeze({ from: first, to: last, raw: rawSource.slice(first, last), parsed: part.content,
      projection: Object.freeze({ starts: Object.freeze(starts as number[]), ends: Object.freeze(ends as number[]),
        boundaries: Object.freeze(Array.from({ length: part.content.length + 1 }, (_, at) => Object.freeze(boundary(part, at)))) }) })
  }
  return {
    parse(environment) {
      if (used) fail('the raw occurrence parse is already sealed')
      used = true
      return captureTokens(normalizedSource(rawSource), environment, tokenText, capture)
    },
    inlineOwner(state) { return capture.owners.get(state.tokens) ?? null },
    inlineRange(state, from, to) {
      const value = capture.inlineTexts.get(state.tokens)
      return value?.content === state.src ? span(value, from, to) : null
    },
    referenceRange(state, startLine, parserSource, from, to) {
      const source = capture.states.get(state)
      if (!source) return null
      const parts: Text[] = []
      let length = 0
      // This is the reference rule's actual getNextLine assembly, using the
      // live StateBlock coordinates (including list/quote/native mutations).
      // Only the exact helper argument is accepted; no text search is used.
      for (let line = startLine; line < state.lineMax && length < parserSource.length; line++) {
        const value = slice(source, state.bMarks[line] + state.tShift[line], Math.min(state.eMarks[line] + 1, source.content.length))
        parts.push(value); length += value.content.length
      }
      const value = concat(parts)
      return value.content === parserSource ? span(value, from, to) : null
    },
    referenceUse(state, token) {
      const source = capture.states.get(state)
      if (!source || !token.map) return null
      const parts: Text[] = []
      for (let line = token.map[0]; line < token.map[1]; line++) parts.push(slice(source,
        state.bMarks[line] + state.tShift[line], Math.min(state.eMarks[line] + (line + 1 < token.map[1] ? 1 : 0), source.content.length)))
      const value = concat(parts)
      return span(value, 0, value.content.length)
    },
    get scopes() { return Object.freeze(capture.scopes.map(value => Object.freeze({
      scope: value.scope, range: span(value.value, 0, value.value.content.length), reason: value.reason
    }))) }
  }
}

export function createMarkdownSourceTrace(raw: string): { port: MarkdownSourceTracePort; finish(): readonly MarkdownSourceContentTrace[] } {
  const normalized = normalizedSource(raw), tokenText = new WeakMap<Token, Text>(), contentTraces: MarkdownSourceContentTrace[] = []
  let finished = false
  let lines: Text[] = [], newlines: Text[] = []
  const rawLines = (start: number, end: number): Text => {
    const parts: Text[] = []
    for (let line = start; line < end; line++) { if (line > start) parts.push(newlines[line - 1]); parts.push(lines[line]) }
    return trimBlank(concat(parts))
  }
  const inline = (token: Token): Text => {
    let value = tokenText.get(token)
    if (!value) fail('missing real token emission for ' + token.type)
    if (token.meta?.nativeLiteralEscaped) value = decode(value)
    if (value.content !== token.content) fail('a token transformation has no exact emission trace: ' + token.type)
    return value
  }
  const port: MarkdownSourceTracePort = {
    parse(source, environment) {
      if (finished) fail('the emission trace is already sealed')
      if (source !== normalized.content) fail('parser input differs from the captured raw source')
      const tokens = captureTokens(normalized, environment, tokenText)
      lines = splitLines(normalized); newlines = []
      let at = 0
      for (const line of lines) { at += line.content.length; newlines.push(slice(normalized, at, at + 1)); at++ }
      const enabled = new Uint8Array(lines.length)
      let legacyEnd = -1
      for (const token of tokens) {
        if (!token.map) continue
        if (['html_details_open', 'html_figure_open'].includes(token.type)) {
          legacyEnd = Math.max(legacyEnd, token.map[1]); enabled.fill(0, ...token.map); continue
        }
        if (token.map[0] < legacyEnd) continue
        const native = token.meta?.nativeContainer as { literalEscaped?: boolean } | undefined
        if (token.type === 'native_container_open' && native) enabled.fill(native.literalEscaped ? 1 : 0, ...token.map)
        else if (['fence', 'code_block', 'math_block', 'frontmatter', 'knowbook_metadata', 'knowbook_database_view'].includes(token.type)) enabled.fill(0, ...token.map)
      }
      lines = lines.map((line, index) => enabled[index] ? decode(line) : line)
      return tokens
    },
    emit(block, index, emission) {
      if (finished) fail('the emission trace is already sealed')
      let value: Text
      let kind: MarkdownSourceContentTrace['kind'] = 'exact'
      if (emission.kind === 'empty') value = generated('')
      else if (emission.kind === 'token') {
        if (emission.token.type === 'knowbook_database_view') {
          const actual = tokenText.get(emission.token)
          if (!actual) fail('missing database fence emission')
          value = actual.content.endsWith('\n') ? slice(actual, 0, actual.content.length - 1) : actual
          // This reserved atom parses and canonicalizes JSON. It has no typed
          // Markdown destinations. Explicitly retain that missing information
          // instead of inventing an exact map or rejecting valid Source Apply.
          if (value.content !== block.content) { value = generated(block.content); kind = 'opaque-generated' }
        } else {
          value = inline(emission.token)
          if (emission.stripFinalLF && value.content.endsWith('\n')) value = slice(value, 0, value.content.length - 1)
        }
      } else if (emission.kind === 'list') {
        const { item, simple, projectedFrom, taskLength } = emission, start = item.token.map![0]
        if (simple) value = protect(inline(item.children[0].children[0].token))
        else {
          const end = projectedFrom < 0 ? item.token.map![1] : item.children[projectedFrom].token.map![0]
          value = trimBlank(protect(stripList(rawLines(start, end)), projectedFrom < 0 ? item.children : item.children.slice(0, projectedFrom), start))
        }
        if (taskLength) value = slice(value, taskLength)
      } else if (emission.kind === 'quote') {
        const { node } = emission
        value = rawLines(...node.token.map!)
        const pieces = splitLines(value), parts: Text[] = []
        let offset = 0
        for (const line of pieces) {
          if (parts.length) parts.push(slice(value, offset - 1, offset))
          const expanded = expandTabs(line), prefix = /^ {0,3}> ?/.exec(expanded.content)?.[0].length ?? 0
          parts.push(slice(expanded, prefix)); offset += line.content.length + 1
        }
        value = protect(concat(parts), node.children, node.token.map![0])
      } else {
        value = rawLines(emission.startLine, emission.endLine)
        if (emission.kind === 'paragraph') for (const match of [...value.content.matchAll(/^ {1,3}(?=\S)/gm)].reverse())
          value = replace(value, match.index, match.index + match[0].length, '')
      }
      if (value.content !== block.content) fail('emission ' + index + ' (' + block.type + ') differs from actual parser content')
      contentTraces.push(Object.freeze({ kind, index, content: value.content,
        starts: Object.freeze(value.starts), ends: Object.freeze(value.ends),
        boundaries: Object.freeze(Array.from({ length: value.content.length + 1 }, (_, at) => Object.freeze(boundary(value, at)))) }))
    }
  }
  return { port, finish() { finished = true; return Object.freeze(contentTraces) } }
}

function validRange(length: number, from: number, to: number): boolean {
  return Number.isSafeInteger(from) && Number.isSafeInteger(to) && from >= 0 && from <= to && to <= length
}
/** Shells, synthetic escapes, deleted ranges and partial decoded entities are
 * not projected. A successful nonempty projection is one continuous span. */
export function projectMarkdownSourceContentRange(trace: MarkdownSourceContentTrace, from: number, to: number): Range | null {
  if (trace.kind !== 'exact') return null
  if (!validRange(trace.content.length, from, to)) return null
  if (from === to) {
    const points = trace.boundaries[from]
    return points?.length === 1 && reverseFor(trace).points.get(points[0])?.length === 1 ? { from: points[0], to: points[0] } : null
  }
  const start = trace.starts[from], end = trace.ends[to - 1]
  if (start === null || start === undefined || end === null || end === undefined) return null
  for (let at = from; at < to; at++) if (trace.starts[at] === null || trace.ends[at] === null
    || at > from && trace.ends[at - 1] !== trace.starts[at]) return null
  return { from: start, to: end }
}
type Reverse = { starts: Map<number, number[]>; ends: Map<number, number[]>; points: Map<number, number[]> }
let reverses: WeakMap<MarkdownSourceContentTrace, Reverse> | undefined
function reverseFor(trace: MarkdownSourceContentTrace): Reverse {
  const cache = reverses ??= new WeakMap<MarkdownSourceContentTrace, Reverse>()
  let reverse = cache.get(trace)
  if (!reverse) {
    reverse = { starts: new Map(), ends: new Map(), points: new Map() }
    const add = (map: Map<number, number[]>, at: number, index: number) => { const values = map.get(at) ?? []; values.push(index); map.set(at, values) }
    for (let index = 0; index < trace.content.length; index++) {
      const start = trace.starts[index], end = trace.ends[index]
      if (start !== null) add(reverse.starts, start, index)
      if (end !== null) add(reverse.ends, end, index + 1)
    }
    trace.boundaries.forEach((points, index) => { if (points.length === 1) add(reverse!.points, points[0], index) })
    cache.set(trace, reverse)
  }
  return reverse
}
export function projectMarkdownSourceRawRange(trace: MarkdownSourceContentTrace, from: number, to: number): Range | null {
  if (trace.kind !== 'exact') return null
  if (!Number.isSafeInteger(from) || !Number.isSafeInteger(to) || from < 0 || to < from) return null
  const reverse = reverseFor(trace)
  if (from === to) { const points = reverse.points.get(from); return points?.length === 1 ? { from: points[0], to: points[0] } : null }
  const starts = reverse.starts.get(from), ends = reverse.ends.get(to)
  if (starts?.length !== 1 || ends?.length !== 1 || starts[0] >= ends[0]) return null
  const result = projectMarkdownSourceContentRange(trace, starts[0], ends[0])
  return result?.from === from && result.to === to ? { from: starts[0], to: ends[0] } : null
}
