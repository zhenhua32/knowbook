import Database from 'better-sqlite3'
import { CAPSULE2_RAW_MAX_JSON_BYTES } from './restore-knowledge-capsule2-raw-model'
import { capsuleJsonStoredArray } from './restore-knowledge-capsule-json-hash'
import { capsuleJson } from './restore-knowledge-capsule-model'
import { graph3Conflict } from './restore-knowledge-graph3-data'

export interface StoredRestoreScopes<Scope> {
  readonly count: number
  /** Use only as part of an input to hashBoundedCapsuleJson. */
  readonly hashInput: readonly Scope[]
  byId(id: string): Scope | undefined
  iterateEncoded(from?: number, until?: number): IterableIterator<string>
  iterate(): IterableIterator<Scope>
}

export function openStoredRestoreScopes<Scope, Projection>(
  produce: (append: (key: string, scope: Scope) => void, store: StoredRestoreScopes<Scope>) => Projection,
  maxEncodedBytes = CAPSULE2_RAW_MAX_JSON_BYTES
) {
  const db = new Database(':memory:')
  try {
    db.pragma('temp_store=FILE')
    if (db.pragma('temp_store', { simple: true }) !== 1) return graph3Conflict('navigation-scope-file-unavailable', null)
    db.pragma('temp.cache_size=-2048')
    db.exec('CREATE TEMP TABLE restore_scopes (ordinal INTEGER PRIMARY KEY, scope_key TEXT NOT NULL UNIQUE, encoded TEXT NOT NULL)')
    const insert = db.prepare('INSERT INTO temp.restore_scopes(ordinal,scope_key,encoded) VALUES(?,?,?)')
    const rows = db.prepare('SELECT encoded FROM temp.restore_scopes ORDER BY ordinal').pluck()
    const range = 'SELECT encoded FROM temp.restore_scopes WHERE ordinal>=? AND ordinal<? ORDER BY ordinal'
    const lookup = db.prepare('SELECT encoded FROM temp.restore_scopes WHERE scope_key=?').pluck()
    let count = 0, encodedBytes = 0
    const encodedRows = (from?: number, until?: number) => (from === undefined && until === undefined ? rows.iterate()
      : db.prepare(range).pluck().iterate(from ?? 0, until ?? count)) as IterableIterator<string>
    const store = Object.freeze({ get count() { return count }, hashInput: capsuleJsonStoredArray<Scope>(encodedRows), iterateEncoded: encodedRows,
      byId(id: string) {
        const encoded = lookup.get(id)
        return typeof encoded === 'string' ? JSON.parse(encoded) as Scope : undefined
      },
      *iterate() {
        for (const encoded of encodedRows()) yield JSON.parse(encoded) as Scope
      } })
    const projection = db.transaction(() => produce((key, scope) => {
      const encoded = capsuleJson(scope)
      encodedBytes += Buffer.byteLength(encoded) + (count ? 1 : 0)
      if (encodedBytes > maxEncodedBytes) return graph3Conflict('navigation-merge-hash-budget', null)
      insert.run(count++, key, encoded)
    }, store))()
    return { projection, store, close: () => { if (db.open) db.close() } }
  } catch (error) {
    db.close()
    throw error
  }
}

/** A synchronous scope for canonical rows generated by a restore planner. */
export function withStoredRestoreScopes<Scope, Projection, Result>(
  produce: (append: (key: string, scope: Scope) => void, store: StoredRestoreScopes<Scope>) => Projection,
  read: (projection: Projection, store: StoredRestoreScopes<Scope>) => Result
): Result {
  const { projection, store, close } = openStoredRestoreScopes(produce)
  try { return read(projection, store) }
  finally { close() }
}
