export interface OriginBundleOriginal {
  readonly directory: string; readonly descriptor: FirstOriginBundleDescriptor; readonly descriptorHash: string
}
const samePath = (a: string, b: string): boolean => process.platform === 'win32' ? a.toLowerCase() === b.toLowerCase() : a === b
const regular = (value: BigIntStats): boolean => value.isFile() && !value.isSymbolicLink() && value.nlink === 1n && value.ino !== 0n
const sameFd = (a: BigIntStats, b: BigIntStats): boolean => regular(a) && regular(b) && a.dev === b.dev && a.ino === b.ino
  && a.size === b.size && a.mtimeNs === b.mtimeNs && a.ctimeNs === b.ctimeNs
const samePathFd = (a: BigIntStats, b: BigIntStats): boolean => regular(a) && regular(b)
  && (a.dev === b.dev || process.platform === 'win32' && (a.dev === 0n || BigInt.asUintN(32, a.dev) === b.dev))
  && a.ino === b.ino && a.size === b.size && a.mtimeNs === b.mtimeNs && a.ctimeNs === b.ctimeNs
async function directory(path: string, root: string): Promise<BigIntStats> {
  await assertRestorePath(path, root)
  const value = await lstat(path, { bigint: true })
  if (!value.isDirectory() || value.isSymbolicLink() || !value.ino || !samePath(await realpath(path), path)) return originBundleInvalid('目录非真实固定owner路径')
  return value
}
async function canonicalRoot(input: string): Promise<string> {
  if (typeof input !== 'string' || !isAbsolute(input) || input.includes('\0') || !samePath(resolve(input), input)) return originBundleInvalid('root不是准确绝对路径')
  const root = await canonicalRestoreRoot(input); await directory(root, root); return root
}
function local(root: string, path: string): string {
  // Paths are generated by the finite model, never descriptor path fields.
  const result = join(root, ...path.split('/')), child = relative(root, result)
  if (!child || child === '..' || child.startsWith('..' + sep) || isAbsolute(child)) return originBundleInvalid('有限catalog路径越界')
  return result
}
async function streamFile(path: string, root: string, expected?: OriginBundleFile, collect = false): Promise<{ bytes: number; sha256: string; content: Buffer | null }> {
  await assertRestorePath(path, root)
  const prior = await lstat(path, { bigint: true })
  if (!regular(prior) || prior.size > BigInt(Number.MAX_SAFE_INTEGER) || collect && prior.size > BigInt(ORIGIN_BUNDLE_MAX_DESCRIPTOR_BYTES)
    || expected && prior.size !== BigInt(expected.bytes)) return originBundleInvalid('原文件非独立有限普通原件或size变化')
  const fd = await open(path, constants.O_RDONLY | (constants.O_NOFOLLOW ?? 0))
  try {
    const before = await fd.stat({ bigint: true })
    if (!samePathFd(prior, before) || process.platform === 'win32' && !before.dev) return originBundleInvalid('原文件打开身份变化或卷未知')
    const buffer = Buffer.alloc(64 * 1024), chunks: Buffer[] = [], digest = createHash('sha256'); let offset = 0
    while (offset < Number(before.size)) {
      const amount = Math.min(buffer.length, Number(before.size) - offset), count = (await fd.read(buffer, 0, amount, offset)).bytesRead
      if (!count) return originBundleInvalid('原文件提前EOF')
      digest.update(buffer.subarray(0, count)); if (collect) chunks.push(Buffer.from(buffer.subarray(0, count))); offset += count
    }
    if ((await fd.read(buffer, 0, 1, offset)).bytesRead) return originBundleInvalid('原文件多余尾bytes')
    const after = await fd.stat({ bigint: true }), current = await lstat(path, { bigint: true }); await assertRestorePath(path, root)
    const sha256 = digest.digest('hex')
    if (!sameFd(before, after) || !samePathFd(current, after) || expected && sha256 !== expected.sha256) return originBundleInvalid('原文件全部bytes/FD/path变化')
    return { bytes: offset, sha256, content: collect ? Buffer.concat(chunks) : null }
  } finally { await fd.close() }
}
async function copyFileExclusive(from: string, sourceRoot: string, to: string, targetRoot: string, expected: OriginBundleFile): Promise<void> {
  await assertRestorePath(from, sourceRoot); await assertRestorePath(to, targetRoot)
  const prior = await lstat(from, { bigint: true })
  if (!regular(prior) || prior.size !== BigInt(expected.bytes)) return originBundleInvalid('复制源不是准确独立文件')
  const source = await open(from, constants.O_RDONLY | (constants.O_NOFOLLOW ?? 0))
  try {
    const before = await source.stat({ bigint: true })
    if (!samePathFd(prior, before) || process.platform === 'win32' && !before.dev) return originBundleInvalid('复制源打开身份变化')
    const target = await open(to, constants.O_WRONLY | constants.O_CREAT | constants.O_EXCL | (constants.O_NOFOLLOW ?? 0), 0o600)
    try {
      const targetBefore = await target.stat({ bigint: true })
      if (!regular(targetBefore) || process.platform === 'win32' && !targetBefore.dev
        || targetBefore.dev === before.dev && targetBefore.ino === before.ino) return originBundleInvalid('新复制不是独立wx原件')
      const buffer = Buffer.alloc(64 * 1024), digest = createHash('sha256'); let offset = 0
      while (offset < expected.bytes) {
        const count = (await source.read(buffer, 0, Math.min(buffer.length, expected.bytes - offset), offset)).bytesRead
        if (!count) return originBundleInvalid('复制源提前EOF')
        digest.update(buffer.subarray(0, count)); let written = 0
        while (written < count) { const next = (await target.write(buffer, written, count - written, offset + written)).bytesWritten; if (!next) return originBundleInvalid('复制目标没有写入'); written += next }
        offset += count
      }
      if ((await source.read(buffer, 0, 1, offset)).bytesRead || digest.digest('hex') !== expected.sha256) return originBundleInvalid('复制源原bytes/hash变化')
      await target.sync()
      const after = await source.stat({ bigint: true }), sourcePath = await lstat(from, { bigint: true }), targetAfter = await target.stat({ bigint: true }), targetPath = await lstat(to, { bigint: true })
      await assertRestorePath(from, sourceRoot); await assertRestorePath(to, targetRoot)
      if (!sameFd(before, after) || !samePathFd(sourcePath, after) || !regular(targetAfter) || !samePathFd(targetPath, targetAfter)
        || targetBefore.dev !== targetAfter.dev || targetBefore.ino !== targetAfter.ino || targetAfter.size !== BigInt(expected.bytes)) return originBundleInvalid('复制期间源/目标身份变化')
    } finally { await target.close() }
  } finally { await source.close() }
}
async function writeDescriptor(path: string, descriptor: FirstOriginBundleDescriptor, root: string): Promise<void> {
  await assertRestorePath(path, root)
  const fd = await open(path, constants.O_WRONLY | constants.O_CREAT | constants.O_EXCL | (constants.O_NOFOLLOW ?? 0), 0o600)
  try {
    const before = await fd.stat({ bigint: true }), bytes = Buffer.from(capsuleJson(descriptor), 'utf8')
    if (!regular(before) || process.platform === 'win32' && !before.dev) return originBundleInvalid('descriptor不是新wx独立文件')
    await fd.writeFile(bytes); await fd.sync()
    const after = await fd.stat({ bigint: true }), current = await lstat(path, { bigint: true }); await assertRestorePath(path, root)
    if (!regular(after) || !samePathFd(current, after) || before.dev !== after.dev || before.ino !== after.ino || after.size !== BigInt(bytes.length)) return originBundleInvalid('descriptor持久化身份变化')
  } finally { await fd.close() }
}
/** One global bounded batch; all started operations and finally FD closes settle
 * before ordered failure escapes or another batch starts. No recursive fanout. */
async function settledBundleBatch<T>(items: Iterable<T>, check: (item: T) => Promise<unknown>): Promise<void> {
  let pending: Promise<unknown>[] = []
  const complete = async (): Promise<void> => {
    const results = await Promise.allSettled(pending)
    pending = []
    for (const result of results) if (result.status === 'rejected') throw result.reason
  }
  for (const item of items) {
    pending.push(Promise.resolve().then(() => check(item)))
    if (pending.length === 4) await complete()
  }
  if (pending.length) await complete()
}
async function exactTree(root: string, descriptor: FirstOriginBundleDescriptor): Promise<void> {
  const files = originBundleExpectedFiles(descriptor), directories = originBundleExpectedDirectories(descriptor)
  type Plan = { key: string; path: string; depth: number; children: Map<string, 'directory' | 'file'> }
  const plans: Plan[] = ['', ...directories].map(key => ({ key, path: key ? local(root, key) : root,
    depth: key ? key.split('/').length : 0, children: new Map<string, 'directory' | 'file'>() }))
  const byKey = new Map(plans.map(plan => [plan.key, plan]))
  const add = (key: string, kind: 'directory' | 'file'): void => {
    const slash = key.lastIndexOf('/'), parent = slash < 0 ? '' : key.slice(0, slash), name = key.slice(slash + 1), plan = byKey.get(parent)
    if (!plan || plan.children.has(name)) return originBundleInvalid('有限catalog计划路径重复或缺父目录')
    plan.children.set(name, kind)
  }
  for (const key of directories) add(key, 'directory')
  for (const file of files) add(file.path, 'file')
  add('descriptor.json', 'file')
  const levels = [...new Set(plans.map(plan => plan.depth))].sort((a, b) => a - b)
  const snapshots = new Map<string, { before: BigIntStats; names: string[] }>(), seenFiles = new Set<string>(), seenDirs = new Set<string>()
  // Ancestor before snapshots precede every child snapshot/read. Same-depth
  // independent directories share one bounded batch, never nested workers.
  for (const level of levels) await settledBundleBatch(plans.filter(plan => plan.depth === level), async plan => {
    const before = await directory(plan.path, root), names = (await readdir(plan.path)).sort(), expected = [...plan.children.keys()].sort()
    if (capsuleJson(names) !== capsuleJson(expected)) return originBundleInvalid('catalog存在额外/缺失文件或目录，含scratch/journal均拒')
    for (const name of names) {
      const info = await lstat(join(plan.path, name), { bigint: true }), kind = plan.children.get(name)
      if (kind === 'directory' ? !info.isDirectory() || info.isSymbolicLink() : !info.isFile() || info.isSymbolicLink())
        return originBundleInvalid('catalog存在额外/错类型文件或目录，含scratch/journal均拒')
    }
    snapshots.set(plan.key, { before, names }); if (plan.key) seenDirs.add(plan.key)
  })
  await settledBundleBatch(files, async file => { await streamFile(local(root, file.path), root, file); seenFiles.add(file.path) })
  // Preserve the descriptor's full inside-tree read as well as the unchanged
  // outer before/after reads; no hash or collected-byte reuse replaces any IO.
  await streamFile(join(root, 'descriptor.json'), root, undefined, true)
  for (const level of [...levels].reverse()) await settledBundleBatch(plans.filter(plan => plan.depth === level), async plan => {
    const prior = snapshots.get(plan.key)
    if (!prior) return originBundleInvalid('完整catalog缺目录快照')
    const after = await directory(plan.path, root)
    if (prior.before.dev !== after.dev || prior.before.ino !== after.ino || prior.before.mtimeNs !== after.mtimeNs || prior.before.ctimeNs !== after.ctimeNs
      || capsuleJson(prior.names) !== capsuleJson((await readdir(plan.path)).sort())) return originBundleInvalid('catalog目录读取期间变化')
  })
  if (seenFiles.size !== files.length || seenDirs.size !== directories.length) return originBundleInvalid('完整catalog缺文件/空index目录')
}
/** Public artifact read is data only. Import owner independently reopens SQL. */
export async function readOriginBundleOriginal(input: string, expectedHash?: string): Promise<OriginBundleOriginal> {
  const root = await canonicalRoot(input), descriptorPath = join(root, 'descriptor.json'), first = await streamFile(descriptorPath, root, undefined, true)
  const text = new TextDecoder('utf-8', { fatal: true, ignoreBOM: true }).decode(first.content!)
  if (!Buffer.from(text, 'utf8').equals(first.content!)) return originBundleInvalid('descriptor不是无损UTF8')
  const descriptor = parseFirstOriginBundleDescriptor(text), descriptorHash = originBundleDescriptorHash(descriptor)
  if (expectedHash !== undefined && descriptorHash !== expectedHash) return originBundleInvalid('descriptor准确hash变化')
  await exactTree(root, descriptor)
  const last = await streamFile(descriptorPath, root, undefined, true)
  if (!first.content!.equals(last.content!)) return originBundleInvalid('catalog读取期间descriptor变化')
  return freezeCapsuleValue({ directory: root, descriptor, descriptorHash })
}
async function makeTree(root: string, descriptor: FirstOriginBundleDescriptor): Promise<void> {
  for (const path of originBundleExpectedDirectories(descriptor)) await restoreDirectory(local(root, path), root)
}
async function syncTree(root: string, descriptor: FirstOriginBundleDescriptor): Promise<void> {
  for (const path of [...originBundleExpectedDirectories(descriptor)].reverse()) await syncRestoreDirectory(local(root, path))
  await syncRestoreDirectory(root)
}
async function syncAncestors(path: string, root: string): Promise<void> {
  let current = path
  for (;;) { await directory(current, root); await syncRestoreDirectory(current); if (samePath(current, root)) return; current = dirname(current) }
}
/** Fixed private-source exporter: no filemap, loader or namespace DTO input. */
export async function writeOriginBundleFromOwnedSource(source: OwnedRequiredRootBundleSource, operationId: string, bundleId: string): Promise<OriginBundleOriginal> {
  const first = await readRequiredRootBundleSource(source), root = await canonicalRoot(first.profileRoot)
  const operation = join(root, 'backups', 'database-restore', durableSqlDagUuid(operationId)), collection = join(operation, 'origin-bundle-exports'), target = join(collection, durableSqlDagUuid(bundleId))
  await restoreDirectory(operation, root); await restoreDirectory(collection, root); await restoreDirectory(target, root, true)
  await makeTree(target, first.descriptor)
  await settledBundleBatch(first.files, file => copyFileExclusive(file.sourcePath, root, local(target, file.path), target, file))
  const last = await readRequiredRootBundleSource(source)
  if (first.descriptorHash !== last.descriptorHash || capsuleJson(first.files) !== capsuleJson(last.files)) return originBundleInvalid('真实source全集复制期间变化')
  await writeDescriptor(join(target, 'descriptor.json'), first.descriptor, target); await syncTree(target, first.descriptor); await syncAncestors(collection, root)
  return readOriginBundleOriginal(target, first.descriptorHash)
}
/** Complete self-contained artifact import. Incoming source is untrusted data;
 * exact descriptor-derived closure/hash is checked before and after copying. */
export async function importOriginBundleOriginal(profile: string, operationId: string, sourceDirectory: string): Promise<{ profileRoot: string; operationId: string; mountId: string; original: OriginBundleOriginal }> {
  const source = await readOriginBundleOriginal(sourceDirectory), profileRoot = await canonicalRoot(profile), op = durableSqlDagUuid(operationId), mountId = randomUUID()
  const operation = join(profileRoot, 'backups', 'database-restore', op), collection = join(operation, 'origin-bundle-mounts'), mount = join(collection, mountId), target = join(mount, 'original')
  await restoreDirectory(operation, profileRoot); await restoreDirectory(collection, profileRoot); await restoreDirectory(mount, profileRoot, true); await restoreDirectory(target, profileRoot, true)
  await makeTree(target, source.descriptor)
  await settledBundleBatch(originBundleExpectedFiles(source.descriptor), file => copyFileExclusive(local(source.directory, file.path), source.directory, local(target, file.path), target, file))
  await readOriginBundleOriginal(source.directory, source.descriptorHash)
  await writeDescriptor(join(target, 'descriptor.json'), source.descriptor, target); await syncTree(target, source.descriptor); await syncAncestors(mount, profileRoot)
  return { profileRoot, operationId: op, mountId, original: await readOriginBundleOriginal(target, source.descriptorHash) }
}
/** Reopen only a fixed Main mount. No external origin locator is guessed. */
export async function readMountedOriginBundle(profile: string, operationId: string, mountId: string, expectedHash: string): Promise<{ profileRoot: string; operationId: string; mountId: string; original: OriginBundleOriginal }> {
  const profileRoot = await canonicalRoot(profile), op = durableSqlDagUuid(operationId), mount = durableSqlDagUuid(mountId)
  const location = join(profileRoot, 'backups', 'database-restore', op, 'origin-bundle-mounts', mount)
  await directory(location, profileRoot)
  const names = await readdir(location)
  if (names.some(name => !['original', 'verification-profiles'].includes(name)) || !names.includes('original')) return originBundleInvalid('mount顶层有未知项目或缺原件')
  return { profileRoot, operationId: op, mountId: mount, original: await readOriginBundleOriginal(join(location, 'original'), expectedHash) }
}
/** Creates a complete independent native-shaped verification profile, not a
 * mount resolution or rewrite. Old verification/scratch dirs are never read. */
export async function createOriginBundleVerificationProfile(input: Awaited<ReturnType<typeof readMountedOriginBundle>>): Promise<string> {
  const actual = await readMountedOriginBundle(input.profileRoot, input.operationId, input.mountId, input.original.descriptorHash)
  const mount = dirname(actual.original.directory), collection = join(mount, 'verification-profiles'), profile = join(collection, randomUUID())
  await restoreDirectory(collection, input.profileRoot); await restoreDirectory(profile, input.profileRoot, true)
  for (const path of originBundleExpectedDirectories(actual.original.descriptor)) {
    if (path === 'catalog') continue
    await restoreDirectory(local(profile, path.slice('catalog/'.length)), profile)
  }
  await settledBundleBatch(originBundleExpectedFiles(actual.original.descriptor), file =>
    copyFileExclusive(local(actual.original.directory, file.path), actual.original.directory, local(profile, file.path.slice('catalog/'.length)), profile, file))
  await readOriginBundleOriginal(actual.original.directory, actual.original.descriptorHash)
  for (const path of [...originBundleExpectedDirectories(actual.original.descriptor)].reverse()) if (path !== 'catalog') await syncRestoreDirectory(local(profile, path.slice('catalog/'.length)))
  await syncRestoreDirectory(profile); await syncAncestors(collection, input.profileRoot)
  return canonicalRoot(profile)
}
